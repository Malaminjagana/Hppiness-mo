const fs = require("node:fs");
const path = require("node:path");

const config = {
  SUPABASE_URL: process.env.SUPABASE_URL || "",
  SUPABASE_ANON_KEY: process.env.SUPABASE_ANON_KEY || "",
  SHOP_NAME: "Jagana African Shop",
  CURRENCY: "GMD"
};

if (!config.SUPABASE_URL || !config.SUPABASE_ANON_KEY) {
  console.warn("Supabase is not configured. Set SUPABASE_URL and SUPABASE_ANON_KEY in Vercel Environment Variables.");
}

const configPath = path.join(__dirname, "js", "config.js");
const generatedConfig = `// Generated by build-config.js from Vercel Environment Variables.\nwindow.JAGANA_CONFIG = ${JSON.stringify(config, null, 2)};\n`;
fs.writeFileSync(configPath, generatedConfig, "utf8");
